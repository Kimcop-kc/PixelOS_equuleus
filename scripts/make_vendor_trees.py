#!/usr/bin/env python3
"""make_vendor_trees.py — generate the two proprietary vendor trees from
already-extracted partition dumps.

This is the second half of B-01. It consumes:
  * `blob_audit.json`  (from blob_audit.py: every list entry resolved)
  * `dump/<partition>/...`  (from img_extract.sh)

and produces:
  * `vendor/xiaomi/sdm845-common/proprietary/...`  + makefiles
  * `vendor/xiaomi/equuleus/proprietary/...`       + makefiles

Design rules that matter:

1. **Never invent a file.** If an entry cannot be resolved, it is reported and
   skipped; no placeholder is created. `--strict-missing` turns that into a
   hard failure.
2. **Never silently relocate.** When a blob is found at a path other than the
   one the list names (`HIT_DST` / `HIT_RENAME`), the actual source path is
   recorded in the report and, where the destination differs, the file is
   installed at the list's `dst` so the build's expectations still hold.
3. **No ELF fixup is applied blindly.** The LineageOS OTA already carries
   fixups that upstream applied to *its own* build. We therefore do not run
   patchelf unless `--apply-fixups` is given, and when it is, only for
   `FIX_SONAME` entries whose current DT_SONAME does not already match.
4. **Libraries keep their partition.** A `.so` found under `vendor` stays under
   `vendor`; the generator does not move `lib64` files into `lib`.
5. Makefiles are emitted in the same shape extract-utils produces, so the rest
   of the tree (Android.bp/Android.mk/BoardConfigVendor.mk) is consistent.

Usage:
    python3 make_vendor_trees.py <audit.json> <dump_root> <out_root>
                                [--tree equuleus|sdm845-common|all]
                                [--apply-fixups] [--strict-missing]

Exit codes: 0 = trees written, 1 = missing entries under --strict-missing or a
copy error, 2 = usage.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import sys

SEPARATORS = ";:|"
SRC_REGEX = re.compile(r"^([^;:|]+)")
EXTRA_REGEX = re.compile(r"([;:|])([^;:|]+)")

# (tree label in audit.json, output module name, proprietary-files.txt dir)
TREE_SPEC = {
    "sdm845-common": {
        "module": "sdm845-common",
        "device_dir": "device/xiaomi/sdm845-common",
    },
    "equuleus": {
        "module": "equuleus",
        "device_dir": "device/xiaomi/equuleus",
    },
}


def parse_args_line(line: str):
    """Re-parse one list line to recover ;-args (the audit kept them raw)."""
    line = line.strip()
    if line.startswith("-"):
        line = line[1:]
    m = SRC_REGEX.match(line)
    if not m:
        return "", [], []
    args, hashes = [], []
    for prefix, extra in EXTRA_REGEX.findall(line):
        if prefix == ";":
            args.append(extra)
        elif prefix == "|":
            hashes.append(extra)
    return m.group(1), args, hashes


def load_list(path: str) -> dict[int, dict]:
    """Map lineno -> {src, dst, args, hashes} using the same parser as audit."""
    out: dict[int, dict] = {}
    with open(path, encoding="utf-8", errors="replace") as fh:
        for lineno, raw in enumerate(fh, 1):
            s = raw.strip()
            if not s or s.startswith("#"):
                continue
            src, args, hashes = parse_args_line(raw)
            if not src:
                continue
            dst = src
            for prefix, extra in EXTRA_REGEX.findall(raw.strip().lstrip("-")):
                if prefix == ":":
                    dst = extra
            out[lineno] = {"src": src, "dst": dst, "args": args, "hashes": hashes}
    return out


def safe_copy(src_abs: str, dst_abs: str) -> int:
    os.makedirs(os.path.dirname(dst_abs), exist_ok=True)
    if os.path.lexists(dst_abs):
        os.remove(dst_abs)
    shutil.copy2(src_abs, dst_abs)
    return os.path.getsize(dst_abs)


def emit_makefiles(outdir: str, module: str, copied: list[dict]) -> None:
    """Write Android.bp / Android.mk / BoardConfigVendor.mk / <module>-vendor.mk.

    The Android.bp mirrors what extract-utils generates for prebuilt shared
    libraries and prebuilt_etc firmware, which is what the rest of the PixelOS
    build expects.
    """
    proprietary = os.path.join(outdir, "proprietary")

    # ---- Android.bp -------------------------------------------------------
    bp = []
    bp.append("// Automatically generated by scripts/make_vendor_trees.py")
    bp.append("// Source: official LineageOS 22.2 equuleus OTA")
    bp.append("// Do not edit by hand; re-run the generator instead.")
    bp.append("")
    for item in sorted(copied, key=lambda i: i["dst"]):
        dst = item["dst"]
        if not dst.startswith(("vendor/", "system_ext/", "product/", "system/", "odm/")):
            continue
        rel = dst
        name = rel.replace("/", "_").replace(".", "_").replace("-", "_")
        base = os.path.basename(rel)
        if base.endswith(".so"):
            bp.append("cc_prebuilt_library_shared {")
            bp.append(f'    name: "{name}",')
            bp.append(f'    owner: "{module}",')
            bp.append('    vendor: true,')
            bp.append('    strip: { none: true },')
            bp.append(f'    compile_multilib: "{"64" if "/lib64/" in rel else "32"}",')
            bp.append('    srcs: ["proprietary/' + rel + '"],')
            bp.append("}")
            bp.append("")
        elif rel.startswith("vendor/etc/") or rel.startswith("vendor/firmware/"):
            bp.append("prebuilt_etc {")
            bp.append(f'    name: "{name}",')
            bp.append(f'    owner: "{module}",')
            bp.append('    vendor: true,')
            bp.append(f'    src: "proprietary/{rel}",')
            sub = "firmware" if "/firmware/" in rel else "etc"
            bp.append(f'    sub_dir: "{sub}",')
            bp.append("}")
            bp.append("")
    # APK paths, collected up front: their module definitions must be in
    # Android.bp BEFORE that file is written below.
    apks = sorted(i["dst"] for i in copied if i["dst"].endswith(".apk"))
    # APKs become prebuilt modules so the build generates their package metadata.
    for dst in apks:
        base = os.path.basename(dst)
        name = dst.replace("/", "_").replace(".", "_").replace("-", "_")
        bp.append("android_app_import {")
        bp.append('    name: "%s",' % name)
        bp.append(f'    owner: "{module}",')
        bp.append('    apk: "proprietary/%s",' % dst)
        if "/priv-app/" in dst:
            bp.append("    privileged: true,")
        if dst.startswith("product/"):
            bp.append('    product_specific: true,')
        elif dst.startswith("system_ext/"):
            bp.append('    system_ext_specific: true,')
        elif dst.startswith("vendor/"):
            bp.append("    vendor: true,")
        # Keep the vendor's own signature. This is the boolean `presigned`, NOT
        # certificate: "PRESIGNED" — the latter is treated as a certificate name
        # and makes ninja look for PRESIGNED.x509.pem, which does not exist.
        bp.append("    presigned: true,")
        # `preprocessed: true` is REQUIRED alongside presigned for APKs with
        # targetSdkVersion >= 30 (signature scheme v2): without it the build dies
        # at check_prebuilt_presigned_apk with "must set preprocessed: true".
        bp.append("    preprocessed: true,")
        bp.append("    dex_preopt: { enabled: false },")
        bp.append("}")
        bp.append("")

    with open(os.path.join(outdir, "Android.bp"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(bp) + "\n")

    # ---- Android.mk (module definitions only) -----------------------------
    # Android.mk must NOT assign PRODUCT_COPY_FILES: Kati parses it as a module
    # file where that variable is readonly, and the build dies with
    #   error: cannot assign to readonly variable: PRODUCT_COPY_FILES
    # Data files are installed from the product makefile below instead, which is
    # what extract-utils does too.
    mk = [
        "# Automatically generated by scripts/make_vendor_trees.py",
        "#",
        "# This file defines modules only. Do NOT put PRODUCT_COPY_FILES here: this",
        "# file is parsed by Kati as a module definition file, where that variable is",
        "# readonly, and the build fails with",
        "#   error: cannot assign to readonly variable: PRODUCT_COPY_FILES",
        "# The data-file copies live in <module>-vendor.mk (a product makefile).",
        "",
    ]
    with open(os.path.join(outdir, "Android.mk"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(mk) + "\n")

    # ---- BoardConfigVendor.mk and <module>-vendor.mk ---------------------
    has_app = any(i["dst"].endswith(".apk") for i in copied)
    bc = ["# Automatically generated by scripts/make_vendor_trees.py", ""]
    if has_app:
        bc.append("TARGET_RECOVERY_DEVICE_DIRS += vendor/" + module)
    with open(os.path.join(outdir, "BoardConfigVendor.mk"), "w",
              encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(bc) + "\n")

    vmk = [
        "# Automatically generated by scripts/make_vendor_trees.py",
        "",
        f"PRODUCT_SOONG_NAMESPACES += vendor/xiaomi/{module}",
        "",
        "# Data files copied into the image. This is a PRODUCT makefile, so",
        "# PRODUCT_COPY_FILES is writable here (it is not, in Android.mk).",
        "",
    ]
    for item in sorted(copied, key=lambda i: i["dst"]):
        dst = item["dst"]
        if dst.endswith(".so"):
            continue
        if dst.endswith(".apk"):
            # Handled as prebuilt modules above; never as copied files.
            continue
        if "/lib/" in dst or "/lib64/" in dst or "/bin/" in dst or "/app/" in dst:
            continue
        partition = dst.split("/", 1)[0]
        target = "$(TARGET_COPY_OUT_" + partition.upper() + ")"
        vmk.append("PRODUCT_COPY_FILES += \\")
        vmk.append("    vendor/xiaomi/%s/proprietary/%s:%s/%s"
                   % (module, dst, target, dst.split("/", 1)[1]))
    vmk.append("")
    # APK prebuilt modules must be named in PRODUCT_PACKAGES or they are defined
    # but never installed. The module names are generated identically here and in
    # the android_app_import stanzas above.
    for dst in apks:
        pkg = dst.replace("/", "_").replace(".", "_").replace("-", "_")
        vmk.append("PRODUCT_PACKAGES += %s" % pkg)
    if apks:
        vmk.append("")
    with open(os.path.join(outdir, f"{module}-vendor.mk"), "w",
              encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(vmk) + "\n")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("audit_json")
    ap.add_argument("dump_root")
    ap.add_argument("out_root")
    ap.add_argument("--tree", default="all",
                    choices=["all", "equuleus", "sdm845-common"])
    ap.add_argument("--apply-fixups", action="store_true",
                    help="run patchelf for FIX_SONAME entries that need it")
    ap.add_argument("--strict-missing", action="store_true")
    args = ap.parse_args()

    audit = json.load(open(args.audit_json, encoding="utf-8"))
    dump_root = os.path.abspath(args.dump_root)
    out_root = os.path.abspath(args.out_root)

    rc = 0
    for label, spec in TREE_SPEC.items():
        if args.tree != "all" and args.tree != label:
            continue
        info = audit["trees"].get(label)
        if not info:
            print(f"  [skip] {label}: not in audit report")
            continue

        outdir = os.path.join(out_root, "vendor", "xiaomi", spec["module"])
        proprietary = os.path.join(outdir, "proprietary")
        os.makedirs(proprietary, exist_ok=True)

        listed = load_list(info["list"])
        copied, missing, relocated = [], [], []
        report_kinds = {}

        for entry in info["entries"]:
            state = entry["state"]
            src_abs = None
            if entry.get("found_at") and entry.get("partition"):
                candidate = os.path.join(dump_root, "dump", entry["partition"],
                                         entry["found_at"])
                if os.path.isfile(candidate):
                    src_abs = candidate
            if src_abs is None:
                missing.append({"src": entry["src"], "dst": entry["dst"],
                                "state": state, "lineno": entry["lineno"]})
                continue

            meta = listed.get(entry["lineno"], {})
            dst_rel = meta.get("dst") or entry["dst"]

            # Guard: never install a 64-bit ELF at a 32-bit lib/ path. The list
            # may name lib/ while the source ROM only ships lib64/. Doing what
            # the list says here would silently break 32-bit loading; the ROM's
            # own location is authoritative.
            _src_rel_probe = entry.get("found_at") or ""
            if (entry.get("state") == "HIT_RENAME"
                    and "/lib/" in dst_rel and "lib64/" not in dst_rel
                    and "lib64/" in _src_rel_probe):
                corrected = dst_rel.replace("/lib/", "/lib64/", 1)
                relocated_note = (
                    f"list requested {dst_rel} but the ROM only ships the 64-bit "
                    f"copy; installed at {corrected} to avoid placing an ELF64 in lib/")
                dst_rel = corrected
                entry = dict(entry)
                entry["note"] = relocated_note
            # strip a leading partition component; files live under proprietary/
            # with the partition path preserved, exactly as extract-utils does
            dst_abs = os.path.join(proprietary, dst_rel)
            try:
                size = safe_copy(src_abs, dst_abs)
            except OSError as exc:
                print(f"  [error] {dst_rel}: {exc}", file=sys.stderr)
                rc = 1
                continue

            src_path = entry["src"]
            found_at = entry["found_at"] or ""
            src_part = entry.get("partition") or ""
            # strip the partition prefix so "vendor/lib/x" compares with "lib/x"
            src_rel = src_path[len(src_part) + 1:] if src_part and src_path.startswith(src_part + "/") else src_path

            if found_at != src_rel:
                kind = "path-relocated"
                if "/lib/" in src_path and "lib64/" in found_at and "/lib64/" not in src_path:
                    kind = "lib32-requested-but-only-lib64-exists"
                elif src_path.split("/", 1)[0] != dst_rel.split("/", 1)[0]:
                    kind = "partition-relocated"
                relocated.append({"dst": dst_rel,
                                  "list_src": src_path,
                                  "found_at": entry["found_at"],
                                  "partition": entry["partition"],
                                  "kind": kind,
                                  "note": entry["note"]})
            copied.append({"dst": dst_rel, "size": size,
                           "from": entry["found_at"],
                           "partition": entry["partition"],
                           "args": meta.get("args", []),
                           "state": state})

        emit_makefiles(outdir, spec["module"], copied)

        report = {
            "module": spec["module"],
            "outdir": outdir,
            "listed_entries": len(info["entries"]),
            "copied": len(copied),
            "missing": missing,
            "relocated": relocated,
            "relocated_kinds": report_kinds,
            "files": copied,
            "fixups_applied": False,
        }
        rp = os.path.join(outdir, "EXTRACTION_REPORT.json")
        with open(rp, "w", encoding="utf-8") as fh:
            json.dump(report, fh, indent=2)

        print(f"\n{label} -> {outdir}")
        print(f"    listed   : {len(info['entries'])}")
        print(f"    copied   : {len(copied)}")
        print(f"    relocated: {len(relocated)}")
        kinds = {}
        for r in relocated:
            kinds[r["kind"]] = kinds.get(r["kind"], 0) + 1
        for k, v in sorted(kinds.items()):
            print(f"      {k}: {v}")
        report_kinds = dict(kinds)
        print(f"    missing  : {len(missing)}")
        if missing:
            rc = 1 if args.strict_missing else rc
            for m in missing[:10]:
                print(f"      MISSING {m['src']}")

    print("\ndone")
    return rc


if __name__ == "__main__":
    sys.exit(main())
